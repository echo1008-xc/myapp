// 三种结果（和文件开头讲的三态一一对应）：
//   ① {kind:'value'} 含碳水、有值 → 显示「GI 83」（值多低都走这条）
//   ② {kind:'zero'}  血糖不动     → 显示「GI 极低」（灰字，不写数值）
//   ③ {kind:'est'}   表里没收录   → 显示「GI 约 45」（按碳水密度估的）
//
// ⚠️ 返回类型里**没有 null 了**（2026-09-28 起）。「GI 无数据」被用户废止：
//    「如果无数据，一定要查。怎么样也要有近似的。这个 App 最重要的就是数据。」
//    —— 所以第二个参数 carbPer100 存在的唯一目的，就是让「查不到」也有答案。
//    调用方要把它算出来：**每 100 克碳水 = 这一项的 carb ÷ grams × 100**。
//
// ⚠️ 那三串字**一律以「GI」打头**（2026-09-25 第六轮定调，继续有效）。
//    界面上看到的最终形态就是上面那三串字；数据层只管给状态，
//    前缀由界面拼 —— 别把「GI」写进 label 里，否则档次名会被污染；
//    也**别把「约」写进 label 里**，同理（界面靠 kind==='est' 自己加）。
//
// 复合菜（土豆炖牛肉、红薯粉丝这类）怎么定值 —— 两条规矩：
//
//   1. **取成分里 GI 最高的那个。**
//      用户 2026-09-25 定调：「这种混合食物的，以其中组成成分当中 GI 最高的为算」。
//      道理：一碗里只要有一样升糖快，整碗就不该按最低的那个报 —— 对控糖的人来说
//      宁可报高一点。所以「土豆炖牛肉」报土豆的 78，不报牛肉的「极低」。
//
//   2. ⚠️ **只在 2 字及以上的词里选；单字词（面 / 饼 / 饭 / 馍 / 粥 / 粉）
//      只在前一步一个都没命中时才轮到。**
//      为什么必须加这条：单字词是「兜底词」，不是成分 ——
//      「面筋」里的「面」、「鲜肉月饼」里的「饼」都不是这道菜的成分。
//      让它们参与比较，结果会被带跑，而且是那种「看着挺合理」的错：
//        · 面筋   会被「面」带到 57（真值 15，面筋是蛋白质做的）
//        · 鲜肉月饼 会被「饼」带到 75（真值 70）
//      2026-09-25 改规则时跑对照实验抓到这两条，所以定了「单字垫底」。
//      同 GI 时取更长的词，保证结果稳定、不受表里书写顺序影响。
export function lookupGi(
  name: string,
  // 这一项每 100 克有多少碳水。查不到名字时用它估一个值。
  // 传 null（或干脆不传）也能用 —— 那时按默认密度给「中」档。
  carbPer100: number | null = null,
): GiInfo {
  const q = (name ?? '').trim();
  if (!q) {
    // 名字是空的（AI 没认出来）：同样不许留空，按碳水估一个。
    return { kind: 'est', ...giFromCarbDensity(carbPer100) };
  }

  // 判断顺序（改这里之前先读一遍，几步是互相咬着的）：
  //   ⓪ 无糖饮料(极低) → ① 鲜米粉 / 湿米粉 / 海鲜粉汤(40) → ② 米磨的粉·糯米粉(87/80)
  //   → ③ 米粉类地名粉(58) → ④ 淀粉制品·土豆粉红薯粉(14/35)
  //   → ⑤ 常规词取 GI 最高（2 字以上）→ ⑥ 单字兜底词
  //   → ⑦「血糖不动」名单(极低) → ⑧ 按碳水密度估（**这一层保证不留空**）
  // ⓪ 必须在最前：「无糖可乐」名字里带「可乐」，晚一步就被 GI 表判成 63。
  // ① 必须在 ③ 前面：「鲜米粉」名字里带「米粉」，顺序一反就判成 58。
  // ② 必须在 ③ 前面：「糯米粉」尾字也是「米粉」，顺序一反就判成 58（真值 87）。

  // ⓪ 先看是不是「无糖版」饮料（无糖可乐 / 零度可乐 / 无糖雪碧……）。
  //    必须在最前面：它们名字里带着「可乐」两个字，晚一步就被 GI 表抢成 63。
  //    理由见上面 SUGAR_FREE_DRINK 的注释。
  for (const k of SUGAR_FREE_DRINK) {
    if (q.includes(k)) {
      return { kind: 'zero', gi: 0, level: giLevel(0) };
    }
  }

  // ① 先看是不是「鲜米粉 / 湿米粉 / 海鲜粉汤」（理由见上面 FRESH_RICE_NOODLE）
  //    ⚠️ 「海鲜米粉」也在这一条里，别再给它加排除 —— 用户 2026-09-25 定：
  //       「海鲜米粉和鲜米粉应该是完全一样」。上一版那道 `if (!q.includes('海鲜'))`
  //       是错的，已删（删掉之后「海鲜米粉」回到 40，见 _gi_meal_test.py 的守门断言）。
  //       「鲜虾米粉」中间隔着字，本来就命中不了，不用管。
  for (const k of FRESH_RICE_NOODLE) {
    if (q.includes(k)) {
      return { kind: 'value', gi: 40, level: giLevel(40) };
    }
  }

  // ② 再看是不是「米磨的粉」（糯米粉 / 粘米粉）。
  //    也排在下面那条**前面** —— 它们尾字就是「米粉」，晚一步被判成 58。
  //    理由见上面 RICE_FLOUR 的注释。
  let flour: { gi: number; len: number } | null = null;
  for (const e of RICE_FLOUR) {
    for (const w of e.words) {
      if (q.includes(w) && (flour === null || w.length > flour.len)) {
        flour = { gi: e.gi, len: w.length };
      }
    }
  }
  if (flour !== null) {
    return { kind: 'value', gi: flour.gi, level: giLevel(flour.gi) };
  }

  // ③ 先看是不是「米粉类地名粉」（要求名字以它结尾，理由见上面 RICE_NOODLE_TAIL）
  for (const k of RICE_NOODLE_TAIL) {
    if (q.endsWith(k)) {
      return { kind: 'value', gi: 58, level: giLevel(58) };
    }
  }

  // ④ 再看是不是淀粉制品（土豆粉 / 红薯粉）：这个必须先于「取成分最高」——
  //    它们是淀粉做出来的，不是「土豆 + 别的东西」，理由见上面 STARCH_NOODLE。
  let starch: { gi: number; len: number } | null = null;
  for (const e of STARCH_NOODLE) {
    for (const w of e.words) {
      if (q.includes(w) && (starch === null || w.length > starch.len)) {
        starch = { gi: e.gi, len: w.length };
      }
    }
  }
  if (starch !== null) {
    return { kind: 'value', gi: starch.gi, level: giLevel(starch.gi) };
  }

  // 在所有「长度 >= minLen」的命中词里，取 GI 最高者（同值取更长的词）
  const pick = (minLen: number): number | null => {
    let gi: number | null = null;
    let hitLen = 0;
    for (const e of GI_DB) {
      for (const k of e.match) {
        if (k.length < minLen || !q.includes(k)) {
          continue;
        }
        if (gi === null || e.gi > gi || (e.gi === gi && k.length > hitLen)) {
          gi = e.gi;
          hitLen = k.length;
        }
      }
    }
    return gi;
  };

  // 先看真正的成分词（2 字以上），没有再看单字兜底词
  const gi = pick(2) ?? pick(1);
  if (gi !== null) {
    return { kind: 'value', gi, level: giLevel(gi) };
  }

  // GI 表没有。再看是不是「血糖基本不动」那类（肉蛋鱼油）——
  // 这类标注的是「极低」，那是一个**实质结论**（吃一份血糖基本不动），
  // 不是「查不到」：界面上它是灰字、不写数值，和「有值 / 估算」都不一样。
  // ⚠️ 这一层必须排在最后那道「按碳水估算」**之前**，顺序不能反 ——
  //    反了的话所有肉蛋蔬菜都会变成估算值（它们碳水密度低，估出来是 30 而不是「极低」）。
  // 同样按「命中的词越长越优先」来选，理由见上面那份名单的注释。
  let zeroLen = 0;
  for (const k of ZERO_GI_MATCH) {
    if (k.length > zeroLen && q.includes(k)) {
      zeroLen = k.length;
    }
  }
  if (zeroLen > 0) {
    return { kind: 'zero', gi: 0, level: giLevel(0) };
  }

  // 两个表都没命中 → **按碳水密度估一个值，不再返回 null**。
  //
  // ⚠️ 2026-09-28 用户定调，把上一版那句「宁可写『无数据』，也不猜一个数」
  //    整个推翻了：「不能有『无数据』这个说法。如果无数据，一定要查。
  //    怎么样也要有近似的。这个 App 最重要的就是数据，你写个『无数据』
  //    还有什么用呢？」
  //    —— 他说的「一定要查」是两层意思：能补进表的就补（这张表已经扫过
  //       十六轮，1165 个常见名字现在 0 个漏网），剩下真查不到的就按碳水估；
  //    —— 估出来的值带「约」字（kind:'est'），和查到的值在界面上分得开，
  //       所以它不是「瞎猜一个数糊弄人」：用户知道这是近似的。
  //    ⚠️ 值的方向一律靠上取，理由见文件开头第 3 条。
  const est = giFromCarbDensity(carbPer100);
  return { kind: 'est', gi: est.gi, level: est.level };
}

