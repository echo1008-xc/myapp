// 常见食物的升糖指数（GI）表 + 五档评定。
//
// 什么是 GI：衡量「含碳水的食物吃下去后，血糖升得多快」。
//   以纯葡萄糖 = 100 为基准，数越小，血糖升得越慢越平稳。
//   它和「有多少碳水」是两件事：西瓜碳水不算多但升得快（GI 72），
//   而同样多的粉丝升得就慢一些。所以两个数字要一起看。
//
// ⚠️ 两条必须守住的口径：
//
//   1. GI 那一栏**只有三种状态，含义彼此不重叠**：
//        有值   = 含可利用碳水，能定出升糖速度（哪怕很低：猪肝 8、豆腐 15）
//        极低   = 吃正常一份，血糖基本不动（肉、蛋、鱼、油、无糖茶咖）
//        约 N   = 表里没收录 → 按这道菜的碳水多少**估**一个（见下面的第 3 条）
//
//      ⚠️⚠️ **「GI 无数据」这个说法 2026-09-28 被用户彻底废止，别再回来**：
//        原话：「GI 无数据这一档要去掉，不能有『无数据』这个说法。如果无数据，
//        一定要查。怎么样也要有近似的。这个 App 最重要的就是数据，你写个
//        『无数据』还有什么用呢？」
//        → 于是 lookupGi 的返回类型里**再也没有 null**，「无数据」这条路
//          在类型层面就被堵死了 —— 不是把文案换掉而已。
//        → 兜底不是瞎给一个数：见下面第 3 条（按碳水密度估）。
//
//      ⚠️ 第二种的界面写法，用户 2026-09-25 当天调了三回，最后定成
//        **写「GI 极低」**（灰字，不写数值）：
//          ① 「无 GI」→ 被他指出「零」和「没有」混在一个说法里；
//          ② 改成数值「GI 0 / 不升糖」→ 他还是觉得不对；
//          ③ 定稿：「原来 GI=0 的全部改成两个字：极低」——
//             因为严格的 GI 表里**根本没有「0 这一档」**，写 0 反而不准确，
//             写「极低」才是这种食物真实的升糖表现。
//
//      ⚠️ 沿革：第三种状态原本是**写「无数据」**（2026-09-25 第五轮定的，
//        当时的理由和上一条同源 —— 三态在界面上都要有个名字，别让人把
//        「没收录」误读成「没碳水」）。**2026-09-28 用户把它推翻了**，
//        理由见下面第 3 条。现在的界面形态是：
//          · GI 83           （表里查到的值，颜色说档位）
//          · GI 极低         （灰字，不写数值：吃一份血糖基本不动）
//          · GI 约 45        （表里没查到 → 按碳水估的，前面那个「约」字
//                              就是他说的「近似的」）
//
//      ⚠️ 「三态一律以『GI』打头」这条**继续有效**（第六轮定的），
//        现在变成了**两态**打头 ——「约」也挂在 GI 后面、值前面：
//          「GI 约 45」。少了 GI 两个字母，单独一个「约 45」没人看得懂。
//
//   3. **表里没收录时，按「这道菜有多少碳水」估一个值 —— 不许留空。**
//      用户 2026-09-28 原话：「不能有『无数据』这个说法。如果无数据，一定要查。
//      怎么样也要有近似的。这个 App 最重要的就是数据，你写个『无数据』还有什么用呢？」
//
//      ⚠️ 为什么用「碳水密度」而不是「再猜一个词」：
//        这张表是按**食物名**查的，而 AI 认出来的名字是无穷的 ——
//        今天补一百个、明天还会冒出新的一百个（已经这样扫过十六轮）。
//        但每一项**已经有碳水和克数了**（云端估的），而碳水密度本身就说明
//        这道菜的主体是什么：密度极低的一定是肉蛋菜，密度极高的一定是主食或糖。
//        所以拿它兜底比继续堆名字更结实，而且**有依据、不是瞎给一个数**。
//      ⚠️ 它的定位是「兜底」，不是「替代」：表里能查到的**一律用表里的值**
//        （那是查过出处的），只有查不到才走这条路。密度分档线见 giFromCarbDensity。
//      ⚠️ 方向上一律**宁可报高**（和「复合菜取成分里最高」同一个原则）：
//        控糖的人看到高一点会少吃一口，看到低一点会多吃一口 —— 后者才是真麻烦。
//
//      ⚠️ 「低」≠「零」≠「没有」。2026-09-25 用户定调：
//      「不应该有 2.0 这条线。任何事物只要有 GI，不管多低都要标出来，
//        它和零和没有是完全不同的两码事。数据准确性合理性就是生命线。」
//
//      → 于是**彻底废掉了「每 100 克碳水 ≤ N 克就写无 GI」这种人为画的线**。
//        那条线我先画成 10 克、又收紧到 2 克，两次都是拍脑袋，
//        两次都被他拿具体食物抓出矛盾（先豆腐、再猪肝）。
//        现在改成按**事实**分，不看碳水数字大小，只看两件事：
//          ① 这种食物含不含可利用碳水？含 → 就该给出值，不管多低。
//          ② 吃一份，血糖到底动不动？确实不动 → 才是「极低」。
//
//      ⚠️ 「极低」的含义是「**吃正常一份血糖基本不动**」，不是「值很小」。
//        依据是实打实的：纯肉每 100 克碳水 1 克上下、鸡蛋 2 克、无糖茶 0 克，
//        一顿的量下去，血糖反应落在测量误差之内 —— 国际 GI 库因此不收录这类
//        食物（测定 GI 要求受试食物含 50 克可利用碳水，肉蛋鱼凑不出这个量）。
//        反过来，豆腐 4 克 / 猪肝 2.5~5 克，一份就有 4~6 克，够让血糖动一动，
//        所以它们**有值**（15 / 8），不能算 0。
//
//      ⚠️ 一句话记牢：**标签的语义必须跟判定依据严格对齐。**
//        「无 GI」这个老说法本身就有歧义（是"没测过"还是"不适用"？），
//        现在一律以「GI」打头，让三态在界面上就不一样：
//        有值 / GI 极低 / GI 约 N（估算）。
//
//   2. 复合菜（宫保鸡丁、土豆炖牛肉这类）**取成分里 GI 最高的那个**。
//      用户 2026-09-25 定调：「这种混合食物的，以其中组成成分当中 GI 最高的为算。」
//      比如「土豆炖牛肉」报土豆的 78，不报牛肉的「极低」——
//      一碗里只要有一样升糖快，整碗就不该按最低的报，对控糖的人宁可报高。
//
//      ⚠️ 但**单字词（面 / 饼 / 饭 / 馍 / 粥 / 粉）只在最后兜底**，
//        不参与「取最高」。它们是兜底词、不是成分：
//        「面筋」里的「面」、「鲜肉月饼」里的「饼」都不是这道菜的成分，
//        让它们参与比较会把结果带跑 —— 面筋会被「面」带到 57（真值 15）。
//        这条是改规则时跑对照实验才发现的，细节见 lookupGi 上方的注释。
//
//      ⚠️ 「取最高」只管 GI 那一栏。**碳水和热量不跟着取最高** ——
//        它们是「按份量比例」累加的（份量 × 每 100 克含量），
//        GI 是食物升糖快慢的属性，两者算法不同、各管各的，
//        不能因为取了高 GI 就把碳水也一起放大。
//
//      ⚠️ 这些值是按主要成分估的，不是实验室测出来的（混合菜没法测）。
//        只用来给人一个量级判断，别当精确值。
//
// 数值取自公开 GI 数据库（悉尼大学 GI 数据库等）的常见区间。
// 同一种食物在不同资料里会差几个点，因为品种、生熟、做法都影响结果
// （比如红薯：煮的 44，烤的能到 94）。这里取「中式家常做法下的代表值」。
// 目标是「档次对」，不是小数点对。
//
// ⚠️ 这张表和 foodDb.ts 是两套独立的东西，各管一件事：
//   foodDb.ts  → 每 100 克有多少热量 / 碳水（跟着克数变）
//   giDb.ts    → 这种食物升糖有多快（不跟克数变，是食物本身的属性）
//   所以这里不用给每条都配热量，反过来 foodDb 也不用配 GI。

import { colors } from '../theme';

// ---------------- 五档评定 ----------------

export type GiLevel = {
  label: string;
  color: string;
};

// 分档沿用了国际通用的两个锚点，把它们拆成了五档：
//   ≤ 55 是「低 GI」（拆成 低 / 较低）
//   56~69 是「中 GI」
//   ≥ 70 是「高 GI」（拆成 较高 / 高）
// 这样既保留了 55、70 这两个公认分界，又能把差别说出来。
export function giLevel(gi: number): GiLevel {
  // ⚠️ 0 不是「五档里最低的那一档」，是**另一种状态**：血糖不动。
  //    标签叫「极低」，界面上写成「GI 极低」（三态一律带 GI 前缀，见开头第 1 条）；
  //    颜色用中性灰，和五档的彩色分开，
  //    扫一眼就知道它不在色阶上 —— 它压根不是色阶上的第六档。
  //    ⚠️ 这个名字改过三回（无 GI → 不升糖 → 极低），沿革见文件开头第 1 条，
  //       别再自己改回去。
  if (gi <= 0) {
    return { label: '极低', color: colors.giZero };
  }
  if (gi <= 45) {
    return { label: '低', color: colors.giLow };
  }
  if (gi <= 55) {
    return { label: '较低', color: colors.giLower };
  }
  if (gi <= 69) {
    return { label: '中', color: colors.giMid };
  }
  if (gi <= 79) {
    return { label: '较高', color: colors.giHigher };
  }
  return { label: '高', color: colors.giHigh };
}

// ---------------- 兜底：表里没收录时，按碳水密度估一个值 ----------------

// 连碳水都拿不到时（认不出重量、碳水准是空的）用的默认密度：
// 落在下面第三档 → 60（中）。取「中」是因为它不偏不倚、又略靠上，
// 和「宁可报高」的原则一致。
const DEFAULT_CARB_PER_100 = 20;

// 「每 100 克有多少碳水」→「这道菜大概升糖多快」。
//
// ⚠️ 这是一个**估算**，不是测量值，界面上一定带一个「约」字（见 lookupGi 末尾）。
//    它的用途只有一个：表里查不到名字时兜底，**绝不留空**。
//
// 分档为什么这么划 —— 密度本身暴露了这道菜的主体是什么：
//   ≤ 5  克/100 克 → 基本是肉、蛋、叶菜、油（例：清蒸鱼 1 克、炒青菜 3 克）
//   5 ~ 12         → 有勾芡、有糖、或掺了少量淀粉的荤菜（例：鱼香肉丝 9 克）
//   12 ~ 25        → 掺了土豆 / 粉条 / 少量主食的菜（例：土豆炖牛肉 15 克）
//   25 ~ 60        → 主食为主（例：白米饭 26 克、馒头 47 克）
//   > 60           → 基本是纯淀粉或糖（例：干粉丝 84 克、白糖 99 克）
// 每一档取的值一律**靠上取**（宁可报高，理由见文件开头第 3 条）。
//
// ⚠️ 别把这张表读成「GI 和碳水有关」—— 那是两码事
//    （西瓜碳水才 8 克，GI 却有 72）。
//    只有「我们不知道它是什么」的时候，密度才是唯一能用的线索。
export function giFromCarbDensity(
  carbPer100: number | null,
): { gi: number; level: GiLevel } {
  const d =
    carbPer100 === null || !isFinite(carbPer100) || carbPer100 < 0
      ? DEFAULT_CARB_PER_100
      : carbPer100;
  const gi = d <= 5 ? 30 : d <= 12 ? 45 : d <= 25 ? 60 : d <= 60 ? 75 : 85;
  return { gi, level: giLevel(gi) };
}

